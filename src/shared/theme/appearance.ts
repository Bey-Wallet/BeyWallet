/** Neutral component subthemes otherwise retain their bundled colors. */
export function createComponentColorThemes() {
  return Object.fromEntries(
    Object.entries(defaultConfig.themes)
      .filter(([name]) =>
        /^(dark|light)_(Input|TextArea|Card|ListItem|SelectTrigger|Tooltip|TooltipContent|TooltipArrow)$/.test(
          name,
        ),
      )
      .map(([name, original]) => {
        const appearance = name.startsWith('dark_') ? 'dark' : 'light';
        const c = appColors[appearance];
        return [
          name,
          {
            ...original,
            ...createAppColorTheme(appearance),
            background: /_(Input|TextArea)$/.test(name) ? c.field : c.surface,
          },
        ];
      }),
  );
}
